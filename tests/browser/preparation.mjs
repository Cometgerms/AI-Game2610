import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  await page.goto(process.env.PREVIEW_URL || 'http://127.0.0.1:5173/');
  await page.getByRole('heading', { name: 'Shape your nation.' }).waitFor();
  assert.equal(await page.getByRole('button', { name: /^Sector / }).count(), 32);
  await page.getByRole('button', { name: 'Choose your nation' }).click();
  await page.getByRole('group', { name: 'Available nations' }).getByRole('button', { name: /^Pelagic Republic/ }).click();
  await page.locator('.template-library summary').click();
  await page.getByRole('button', { name: /^Use: Liberal republic/ }).click();
  const intent = page.getByRole('textbox', { name: 'Write your founding doctrine' });
  await intent.fill('Protect the capital. Invest in research. 保卫首都。');
  await page.getByRole('textbox', { name: 'Template name' }).fill('Armed neutrality');
  await page.getByRole('button', { name: 'Save template', exact: true }).click();
  assert.match(await page.locator('.template-status').innerText(), /Template saved/);
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  assert.match(await page.locator('.notice').innerText(), /saved on this device/);
  await page.reload();
  assert.match(await page.getByRole('button', { name: 'Choose your nation' }).innerText(), /Pelagic Republic/);
  assert.equal(await intent.inputValue(), 'Protect the capital. Invest in research. 保卫首都。');
  await page.locator('.template-library summary').click();
  await page.getByRole('button', { name: /^Use: Planned economy/ }).click();
  await page.getByRole('button', { name: /^Load: Armed neutrality/ }).click();
  assert.equal(await intent.inputValue(), 'Protect the capital. Invest in research. 保卫首都。');
  await intent.fill('Revised doctrine. 保持中立。');
  await page.getByRole('button', { name: 'Update template' }).click();
  await page.reload();
  await page.locator('.template-library summary').click();
  await page.getByRole('button', { name: /^Load: Armed neutrality/ }).click();
  assert.equal(await intent.inputValue(), 'Revised doctrine. 保持中立。');
  assert.equal(await page.locator('.saved-template').count(), 1);
  await page.locator('.template-library summary').click();
  const originalMap = await page.locator('.terrain-region').first().getAttribute('d');
  await page.getByRole('button', { name: 'New terrain' }).click();
  assert.notEqual(await page.locator('.terrain-region').first().getAttribute('d'), originalMap);
  assert.ok(await page.locator('.terrain-dots > circle').count() > 4000);
  const cloud = await page.locator('.terrain-dots > circle').nth(800).getAttribute('cy');
  await page.getByRole('slider', { name: /Terrain height/ }).fill('0');
  assert.notEqual(await page.locator('.terrain-dots > circle').nth(800).getAttribute('cy'), cloud);
  await page.getByRole('slider', { name: /Terrain height/ }).fill('1');
  await page.locator('.test-parameters summary').click();
  const industry = page.getByRole('slider', { name: /Industry/ });
  await industry.fill('100');
  assert.deepEqual(await page.locator('.slider-row output').allTextContents(), ['100%', '0%', '0%']);
  await page.locator('.test-parameters summary').click();
  await page.getByRole('button', { name: 'Preview deployment' }).click();
  await page.getByRole('heading', { name: 'Survey your world.' }).waitFor();
  await page.getByRole('button', { name: /Sector 1,/ }).focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.getByRole('button', { name: /Sector 1,/ }).getAttribute('aria-pressed'), 'true');
  assert.equal(await page.getByRole('button', { name: /Sector 1,/ }).evaluate(element => getComputedStyle(element).outlineStyle), 'none');
  assert.equal(await page.getByRole('button', { name: /Sector 1,/ }).evaluate(element => getComputedStyle(element).strokeWidth), '3px');
  assert.equal(await page.getByRole('button', { name: 'New terrain' }).isDisabled(), true);
  await page.getByRole('button', { name: 'Revise doctrine' }).click();
  await page.getByRole('button', { name: 'Switch to Chinese' }).click();
  await page.getByRole('heading', { name: '塑造你的国家。' }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: '写下你的建国方针' }).inputValue(), 'Revised doctrine. 保持中立。');
  await page.locator('.template-library summary').click();
  await page.getByRole('button', { name: /^使用：计划经济/ }).click();
  assert.match(await page.getByRole('textbox', { name: '写下你的建国方针' }).inputValue(), /国营工业/);
  await page.locator('.template-library summary').click();
  await mkdir('build/screenshots', { recursive: true });
  await page.screenshot({ path: 'build/screenshots/preparation-zh-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '切换为英文' }).click();
  await page.locator('.template-library summary').click();
  await page.getByRole('button', { name: /^Use: Planned economy/ }).click();
  await page.locator('.template-library summary').click();
  await page.screenshot({ path: 'build/screenshots/preparation-en-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout overflows horizontally.');
  await page.getByRole('button', { name: 'Preview deployment' }).click();
  await page.getByRole('heading', { name: 'Survey your world.' }).waitFor();
  await page.getByRole('button', { name: 'Revise doctrine' }).click();
  await page.screenshot({ path: 'build/screenshots/preparation-mobile.png', fullPage: true });
  assert.deepEqual(failures, [], 'Browser runtime errors.');
  console.log('PASS: named text template create/update/reload, draft persistence, budget conservation, point-cloud elevation, unequal territory, seed regeneration, accessible contour focus, bilingual intent preservation and mobile layout.');
} finally {
  await browser.close();
}
